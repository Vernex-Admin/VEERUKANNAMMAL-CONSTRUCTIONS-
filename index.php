function setupScrollListener() {
    // Hide scroll indicator after user scrolls a bit
    let hasScrolled = false;
    
    function onScroll() {
        if (!hasScrolled) {
            hasScrolled = true;
            const scrollIndicator = document.getElementById('scrollIndicator');
            if (scrollIndicator) {
                setTimeout(() => {
