// Mobile performance optimizations
document.addEventListener('DOMContentLoaded', function() {
    // Optimize images for mobile
    if (window.innerWidth < 768) {
        // Lazy load images on mobile
        const images = document.querySelectorAll('img[data-src]');
        const imageObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const img = entry.target;
                    img.src = img.dataset.src;
                    img.classList.remove('lazy');
                    imageObserver.unobserve(img);
                }
            });
        });

        images.forEach(img => imageObserver.observe(img));

        // Reduce carousel autoplay speed on mobile
        if (typeof $ !== 'undefined') {
            $('.owl-carousel').each(function() {
                const carousel = $(this);
                if (carousel.data('owl.carousel')) {
                    carousel.data('owl.carousel').settings.autoplayTimeout = 5000;
                }
            });
        }

        // Optimize touch events
        document.addEventListener('touchstart', function() {}, { passive: true });
        document.addEventListener('touchmove', function() {}, { passive: true });
    }

    // Smooth scroll for mobile
    const links = document.querySelectorAll('a[href^="#"]');
    links.forEach(link => {
        link.addEventListener('click', function(e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                const headerHeight = document.querySelector('.main-bar').offsetHeight;
                const targetPosition = target.getBoundingClientRect().top + window.pageYOffset - headerHeight;

                window.scrollTo({
                    top: targetPosition,
                    behavior: 'smooth'
                });
            }
        });
    });

    // Mobile-friendly modal handling
    const modals = document.querySelectorAll('.modal');
    modals.forEach(modal => {
        modal.addEventListener('show.bs.modal', function() {
            document.body.style.overflow = 'hidden';
        });

        modal.addEventListener('hide.bs.modal', function() {
            document.body.style.overflow = '';
        });
    });

    // Optimize contact form for mobile
    const contactForm = document.getElementById('contactForm');
    if (contactForm) {
        const inputs = contactForm.querySelectorAll('input, textarea');
        inputs.forEach(input => {
            // Prevent zoom on iOS
            if (/iPhone|iPad|iPod/.test(navigator.userAgent)) {
                input.addEventListener('focus', function() {
                    this.style.fontSize = '16px';
                });
            }
        });
    }

    // Mobile carousel optimizations
    if (typeof $ !== 'undefined') {
        // Reduce slides on mobile
        $('.home-client-carousel-2').owlCarousel({
            responsive: {
                0: { items: 2, margin: 10 },
                480: { items: 3, margin: 15 },
                768: { items: 4, margin: 20 }
            }
        });

        // Optimize testimonial carousel for mobile
        $('.testimonial-home').owlCarousel({
            responsive: {
                0: { items: 1, margin: 10, stagePadding: 20 },
                768: { items: 2, margin: 30 }
            }
        });

    }
});

